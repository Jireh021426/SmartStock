
-- SmartStock - Supplier Management
-- PostgreSQL schema migration
-- Creates the supplier table without modifying
-- existing inventory, sales, or financial tables.
--
-- IMPORTANT:
-- This file must be executed explicitly.
-- Spring Boot will not run it automatically.

BEGIN;

CREATE TABLE IF NOT EXISTS public.supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    code VARCHAR(40) NOT NULL,

    name VARCHAR(150) NOT NULL,

    contact_number VARCHAR(50),

    address VARCHAR(255),

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP(6) WITHOUT TIME ZONE
        NOT NULL DEFAULT LOCALTIMESTAMP,

    CONSTRAINT pk_supplier PRIMARY KEY (id),

    CONSTRAINT uk_supplier_code UNIQUE (code)
);

COMMIT;
