-- Additive historical source-evidence tables.
-- These tables NEVER change inventory, recorded sales, or customers' live balances.
BEGIN;
CREATE TABLE IF NOT EXISTS public.historical_day (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES public.stock_location(id),
    business_date DATE NOT NULL,
    collections NUMERIC(16,2) NOT NULL CHECK (collections >= 0),
    source_file VARCHAR(255) NOT NULL,
    notes VARCHAR(1000) NOT NULL,
    debts_complete BOOLEAN NOT NULL DEFAULT FALSE,
    stock_complete BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    recorded_by VARCHAR(100) NOT NULL,
    recorded_at TIMESTAMP NOT NULL,
    last_edited_by VARCHAR(100),
    last_edited_at TIMESTAMP,
    reviewed_by VARCHAR(100),
    reviewed_at TIMESTAMP,
    review_note VARCHAR(1000),
    CONSTRAINT uk_historical_day_location_date UNIQUE(location_id, business_date)
);
CREATE TABLE IF NOT EXISTS public.historical_debt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_id BIGINT NOT NULL REFERENCES public.historical_day(id),
    customer_name VARCHAR(100) NOT NULL,
    customer_key VARCHAR(100) NOT NULL,
    closing_balance NUMERIC(16,2) NOT NULL CHECK (closing_balance >= 0),
    CONSTRAINT uk_historical_debt_day_customer UNIQUE(day_id, customer_key)
);
CREATE TABLE IF NOT EXISTS public.historical_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_id BIGINT NOT NULL REFERENCES public.historical_day(id),
    product_name VARCHAR(100) NOT NULL,
    product_key VARCHAR(110) NOT NULL,
    unit VARCHAR(5) NOT NULL CHECK (unit IN ('KG','PCS')),
    available_qty NUMERIC(14,3) NOT NULL CHECK (available_qty >= 0),
    closing_qty NUMERIC(14,3) NOT NULL CHECK (closing_qty >= 0),
    known_loss_qty NUMERIC(14,3) NOT NULL CHECK (known_loss_qty >= 0),
    selling_price NUMERIC(12,2) NOT NULL CHECK (selling_price >= 0),
    CONSTRAINT ck_historical_stock_balance CHECK (closing_qty + known_loss_qty <= available_qty),
    CONSTRAINT uk_historical_stock_day_product UNIQUE(day_id, product_key)
);
CREATE INDEX IF NOT EXISTS idx_historical_day_date ON public.historical_day(business_date);
CREATE INDEX IF NOT EXISTS idx_historical_debt_day ON public.historical_debt(day_id);
CREATE INDEX IF NOT EXISTS idx_historical_stock_day ON public.historical_stock(day_id);
COMMIT;
