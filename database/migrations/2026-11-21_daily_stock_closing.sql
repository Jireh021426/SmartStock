-- Additive, non-destructive migration; required before deploying daily closings.
BEGIN;

CREATE TABLE IF NOT EXISTS public.daily_stock_closing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES public.stock_location(id),
    product_id BIGINT NOT NULL REFERENCES public.product(id),
    business_date DATE NOT NULL,
    book_kg NUMERIC(14,3) NOT NULL,
    counted_kg NUMERIC(14,3) NOT NULL,
    recorded_sales_kg NUMERIC(14,3) NOT NULL,
    recorded_revenue NUMERIC(16,2) NOT NULL,
    unit_price_snapshot NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    counted_by VARCHAR(100) NOT NULL,
    counted_at TIMESTAMP NOT NULL,
    count_note VARCHAR(1000) NOT NULL,
    reviewed_by VARCHAR(100),
    reviewed_at TIMESTAMP,
    review_note VARCHAR(1000),
    CONSTRAINT ck_closing_nonnegative CHECK (
        book_kg >= 0 AND counted_kg >= 0 AND recorded_sales_kg >= 0
        AND recorded_revenue >= 0 AND unit_price_snapshot >= 0)
);

CREATE INDEX IF NOT EXISTS idx_daily_closing_date_location
    ON public.daily_stock_closing(business_date, location_id);

COMMIT;
